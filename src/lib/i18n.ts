export const STRINGS: Record<UiLang, Record<I18nKey, string>> = { en, fa }
export function tr(lang: UiLang, key: I18nKey): string { return STRINGS[lang][key] ?? STRINGS.en[key] ?? key }
export function resolveUiLang(input?: string | null): UiLang { return input === 'fa' ? 'fa' : 'en' }
export function loadUiLang(storage: Pick<Storage, 'getItem'>): UiLang { try { return resolveUiLang(storage.getItem(UI_LANG_KEY)) } catch { return 'en' } }
export function saveUiLang(storage: Pick<Storage, 'setItem'>, lang: UiLang): void { try { storage.setItem(UI_LANG_KEY, lang) } catch { /* best-effort */ } }
export function uiDir(lang: UiLang): 'rtl' | 'ltr' { return lang === 'fa' ? 'rtl' : 'ltr' }
